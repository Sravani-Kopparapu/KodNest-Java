
class Concat {

    public static void main(String[] args) {
        String s1 = "Java";
        String s2 = "Tech";
        String s3 = s1 + s2;
        System.out.println(s3);

        String t1 = new String("Arshit");
        String t2 = new String("Ramu");
        String res = t1.concat(t2);
        System.out.println(res);
    }
}
